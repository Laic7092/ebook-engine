    let cp = c as u32;
    let mut lo = 0usize;
    let mut hi = RANGE_COUNT;
    while lo < hi {
        let mid = (lo + hi) / 2;
        let (start, end, class) = RANGES[mid];
        if cp < start {
            hi = mid;
        } else if cp > end {
            lo = mid + 1;
        } else {
            return class;
        }
    }
